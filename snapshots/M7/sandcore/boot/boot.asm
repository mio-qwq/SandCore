; =====================================================================
;  SandCore OS —— 一级引导器 (boot/boot.asm)
;  ---------------------------------------------------------------------
;  【这是什么】
;    按下电源后, BIOS 先做 POST 自检, 然后按启动顺序找到启动盘,
;    把它的第一个扇区(512 字节)原样复制到内存 0x7C00 处,
;    最后跳过去执行 —— 本文件就是那 512 字节。
;    我们不用 GRUB/LILO 等任何现成引导器, 从这里开始全靠自己。
;
;  【本引导器要做的四件事】
;    1. 用 BIOS int 13h 把内核从磁盘读进内存 0x10000
;    2. 把显卡切到 VGA 13h 图形模式 (320x200, 256 色)
;    3. 打开 A20 地址线, 建立自己的 GDT, 切入 32 位保护模式
;    4. 跳到内核入口 0x10000, 从此一去不回
;
;  【交接时的约定】(详见 docs/BOOT.md)
;    - CPU: 32 位保护模式, CPL0, 平坦段(基址 0 / 上限 4GB)
;    - 显卡: 已处于 VGA 13h 模式, 线性显存 0xA0000, 一字节一像素
;    - 内存: 内核已就位于 0x10000; 栈顶在 0x90000 附近
;    - BIOS 服务: 进入保护模式后全部失效, 内核不得再调用
; =====================================================================
[bits 16]                 ; 告诉 NASM: 按 16 位实模式编码
[org 0x7C00]              ; 告诉 NASM: 本代码运行时位于 0x7C00 (算标号地址用)

; ---------------------------------------------------------------------
; 构建期常量
;   这几个数字同时约束 tools/mkimg.py 的镜像打包格式,
;   任何一处改动都必须同步修改另一处!
; ---------------------------------------------------------------------
KERNEL_SEG    equ 0x1000  ; 内核装载段地址 -> 线性地址 0x1000*16 = 0x10000
KERNEL_LBA    equ 1       ; 内核从磁盘 LBA 1 开始 (LBA 0 = 引导扇区自己)
KERNEL_SECTS  equ 256     ; M7：最多 128KB；ES 每扇前移，跨 64KB 不会回绕 BX

SPT           equ 18      ; 1.44MB 软盘几何: 每磁道 18 扇区
HPC           equ 2       ;                  两个磁头(盘的两面)
                          ; 80 柱面 x 2 面 x 18 扇区 x 512B = 1474560B

; =====================================================================
;  入口: BIOS 跳到这里时 DL = 启动盘号, 其余段寄存器值不可靠
; =====================================================================
start:
    ; ---- 第 0 步: 建立干净的运行环境 ----
    cli                       ; 关中断: 换段寄存器/换栈的半途不能被打断
    xor ax, ax
    mov ds, ax                ; 数据段归零 -> 代码里的 [符号] 直接就是线性地址
    mov es, ax
    mov ss, ax
    mov sp, 0x7C00            ; 栈顶压在代码正下方, 向下生长, 互不干扰
    sti                       ; 开中断 (BIOS 的磁盘/显示服务内部需要)
    mov [boot_drive], dl      ; BIOS 约定 DL = 启动盘号(0x00=软盘A), 存下来

    mov si, msg_boot          ; 先用 BIOS 文本服务打一行进度
    call print                ; (此时还是 80x25 文本模式)

    ; -----------------------------------------------------------------
    ; E820 内存图采集 (只能在实模式干, 这是最后的机会!)
    ; int 15h AX=E820: BIOS 每次把一条"地址范围描述符"写到 ES:DI
    ;   入口: EBX=续读游标(首轮 0)  ECX=20(只要基础 20 字节)
    ;         EDX='SMAP' 魔数       ES:DI=输出缓冲
    ;   出口: CF=0 成功且 EAX 回读 'SMAP'; EBX=下次游标(0=采集完)
    ; 我们把它规格化成 24 字节条目 (基址8 + 长度8 + 类型8) 存到
    ; 0x7E04 起, 条数存 0x7E00 —— 内核从这里读 (docs/BOOT.md 契约 v0.3)
    ; -----------------------------------------------------------------
    mov dword [0x7E00], 0     ; 条数清零
    mov di, 0x7E04            ; ES=0, 直接写 0:0x7E04
    xor ebx, ebx              ; 游标 = 0 (首轮)
.e820:
    mov edx, 0x534D4150       ; 'SMAP'
    mov ecx, 20
    mov eax, 0xE820
    int 0x15
    jc .e820_done             ; CF=1: BIOS 不支持或已完
    cmp eax, edx              ; EAX 必须回读 'SMAP'
    jne .e820_done
    ; 规格化: BIOS 的 20 字节条目 (基址32/基址高32/长32/长高32/类型32)
    ; 恰好就是 24 字节条目 (基址64/长64/类型64) 的前 20 字节 ——
    ; 只需把三个高位双字清零, 千万别搬数据!
    ; 【M2 调试实录】这里曾经"好心"重排过, 把类型搬进了下一条目的
    ; 地盘, 内核读到的全是错位数据 (长度 0 / 类型 other)。
    mov dword [di+20], 0      ; 类型 64 位的高 32 位 = 0
    add di, 24
    inc dword [0x7E00]
    cmp dword [0x7E00], 32
    jae .e820_done            ; 最多记 32 条
    test ebx, ebx
    jnz .e820                 ; EBX=0: 采集完毕
.e820_done:

    ; -----------------------------------------------------------------
    ; 第 1 步: 把内核读进 0x10000
    ; -----------------------------------------------------------------
    ; 【M2 调试实录】曾按"每轮最多读一道"成块读: M1 内核 (17 扇区,
    ; 单道) 一直正常; M2 内核涨到 24 扇区, 第一次跨磁道, 从第二道起
    ; 读回来的全是 0 —— 多扇区跨道读在 QEMU 虚拟 FDC + BIOS 组合下
    ; 不可靠。改成一次读一扇, 慢几毫秒, 换来百发百中。
    ;
    ; LBA -> CHS:  扇区 = LBA mod SPT + 1 (1 基)
    ;              磁头 = (LBA / SPT) mod HPC
    ;              柱面 = LBA / (SPT * HPC)
    ; 内存前进: BX 恒 0, 每读一扇 ES 前移 32 段 (512B / 16)。
    ; -----------------------------------------------------------------
    mov ax, KERNEL_SEG
    mov es, ax                ; ES:BX = 0x1000:0000 = 线性 0x10000
    xor bx, bx
    mov word [lba],   KERNEL_LBA   ; 当前要读的逻辑扇区号
    mov word [left],  KERNEL_SECTS ; 还剩多少扇区没读
    mov word [tries], 4            ; 失败重试预算

.read:
    mov ax, [lba]
    xor dx, dx
    div word [spt]            ; AX = LBA/SPT, DX = 道内扇区号 (0 基)
    push dx                   ; 存下, 待会换 1 基
    xor dx, dx
    div word [hpc]            ; AX = 柱面, DX = 磁头
    mov dh, dl                ; DH = 磁头
    pop cx
    inc cx                    ; CX = 扇区号 (1 基; 此举会把 CH 冲成 0!)
    mov ch, al                ; CH = 柱面 —— 必须最后设!
                              ; 【M3 调试实录】曾经先设 CH 后算 CX,
                              ;   柱面 ≥1 的读取全部读错地方 (0x8e 变 0x00)
    mov ah, 0x02              ; int 13h: 读扇区 —— 一次一枚
    mov al, 1
    mov dl, [boot_drive]
    int 0x13
    jnc .ok

    dec word [tries]          ; 失败: 复位磁盘控制器 (AH=0) 再重试
    jz .fail
    xor ax, ax                ; int 13h AH=00: 复位软盘系统
    int 0x13
    jmp .read

.ok:
    mov ax, es
    add ax, 32                ; 前进 512B = 32 段
    mov es, ax
    inc word [lba]
    dec word [left]
    jnz .read

    mov si, msg_run
    call print

    ; -----------------------------------------------------------------
    ; 第 2 步: 切换 VGA 13h 图形模式
    ;   int 10h AH=00, AL=模式号: 0x13 = 320x200, 256 色
    ;   此后 BIOS 会清屏并把显存布局改成"线性"的:
    ;   0xA0000 起连续 64000 字节, 一个字节一个像素, 字节值 = 调色板号。
    ;   这是 13h 模式最大的好处: 画点无需碰端口, 直接写内存。
    ; -----------------------------------------------------------------
    mov ax, 0x0013
    int 0x10

    ; -----------------------------------------------------------------
    ; 第 3 步: 打开 A20 地址线
    ;   历史包袱: 8086 只有 20 根地址线, 第 21 根(A20)被强制拉零以兼容
    ;   老程序回绕。不打开它, 访问奇数 1MB 边界以上的地址会被截断。
    ;   端口 0x92 是"快速 A20 门": bit1 = A20 使能, bit0 = 快速复位
    ;   (必须保持 0, 置 1 会重启 CPU!)。先读出原值再改写。
    ; -----------------------------------------------------------------
    in al, 0x92
    or al, 0x02               ; 置 A20 使能位
    and al, 0xFE              ; 清快速复位位 (只是保险, 通常本来就是 0)
    out 0x92, al

    ; -----------------------------------------------------------------
    ; 第 4 步: 进入 32 位保护模式
    ;   保护模式里"段"不再是 段寄存器*16, 而变成查 GDT(全局描述符表)
    ;   的索引。GDT 每条 8 字节, 定义一个段的基址/上限/属性。
    ; -----------------------------------------------------------------
    cli                       ; 进入保护模式前必须关中断:
                              ; 实模式的中断向量表(IVT)在保护模式下无效,
                              ; 此刻来一个中断就会跳进未知代码
    lgdt [gdt_desc]           ; 把我们的 GDT 位置和长度装进 GDTR 寄存器
    mov eax, cr0
    or eax, 1                 ; CR0 的 bit0 = PE(Protection Enable)
    mov cr0, eax              ; 置位瞬间 CPU 进入保护模式,
                              ; 但 CS 还缓存着实模式语义, 必须立刻远跳刷新
    jmp 0x08:pm_entry         ; 远跳: 同时装载 CS=0x08 (代码段选择子)
                              ; 并清空流水线 —— 保护模式的成人礼

.fail:
    mov si, msg_fail
    call print
.hang16:
    hlt                       ; 没救了, 停机等下一个中断
    jmp .hang16

; =====================================================================
;  32 位保护模式的世界
; =====================================================================
[bits 32]
pm_entry:
    ; 数据类段寄存器全部换成数据段选择子 0x10 (平坦 0..4GB)
    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov fs, ax
    mov gs, ax
    mov esp, 0x90000          ; 内核栈: 0x90000 向下生长
                              ; (下方 0x18000 处是内核, 上方 0x9FC00 处
                              ;  是 BIOS 保留区 EBDA, 都不冲突)
    call 0x10000              ; 跳进内核入口 (kernel/entry.asm 的 _start)
                              ; 内核永不返回; 万一返回了就掉进下面的死循环

.halt:
    hlt
    jmp .halt

; =====================================================================
;  BIOS 字符打印 (teletype)
;   int 10h AH=0Eh: AL=字符, BL=颜色(文本模式), 打完自动前进光标
;   只在引导期用, 保护模式下不可用
; =====================================================================
[bits 16]
print:
    pusha
.next:
    lodsb                     ; AL = [DS:SI], SI++
    or al, al
    jz .done                  ; 0 结尾
    mov ah, 0x0E
    mov bx, 0x0007            ; 页面 0, 颜色 7(浅灰)
    int 0x10
    jmp .next
.done:
    popa
    ret

; =====================================================================
;  数据区
; =====================================================================
msg_boot db "SandCore: loading kernel...", 0
msg_run  db " ok, protected mode", 13, 10, 0
msg_fail db "SandCore: disk error!", 0

boot_drive db 0                ; BIOS 交给我们的启动盘号
lba    dw 0                    ; 读盘状态: 当前逻辑扇区
left   dw 0                    ;           剩余扇区数
cnt    dw 0                    ;           本轮读取数
tries  dw 0                    ;           剩余重试机会
spt    dw SPT                  ; 除法用的几何常量 (div 只能除内存/寄存器)
hpc    dw HPC

; ---- GDT: 3 条描述符, 每条 8 字节, 位域含义 (从低位到高位):
;   [15:0]  段上限低 16 位
;   [39:16] 段基址低 24 位
;   [47:40] 访问字节: P存在 | DPL特权级 | S系统/代码数据 | TYPE类型
;   [51:48] 段上限高 4 位
;   [55:52] 标志: G粒度(1=4K页) | D默认操作数(1=32位) | L | AVL
;   [63:56] 段基址高 8 位
; ----
align 8
gdt:
    dq 0                          ; [0] 空描述符, CPU 规定
    dq 0x00CF9A000000FFFF         ; [1] 0x08 代码段: 基址0 上限4G
                                  ;     访问=0x9A: P=1 DPL=0 S=1 代码可执行可读
                                  ;     标志=0xC : 4K 粒度 + 32 位
    dq 0x00CF92000000FFFF         ; [2] 0x10 数据段: 同上但可读写(0x92)
gdt_desc:
    dw gdt_desc - gdt - 1         ; GDT 上限 = 字节数 - 1 = 23
    dd gdt                        ; GDT 线性基址 (DS 基址为 0, 符号即线性)

; ---------------------------------------------------------------------
; 收尾: 补 0 到 510 字节, 最后两字节是引导扇区魔数 0xAA55。
; BIOS 就靠这两个字节判断"这个盘是不是可以引导"。
; ---------------------------------------------------------------------
times 510-($-$$) db 0
dw 0xAA55
