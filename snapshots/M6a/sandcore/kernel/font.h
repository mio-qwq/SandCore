/* 查字形: 0x20..0x7E 直查, 越界一律给空格 (第 0 项全零) */
static const unsigned char *glyph_of(char ch)
{
    unsigned c = (unsigned char)ch;
    if (c < 0x20 || c > 0x7E)
        c = 0x20;
    return sc_font[c - 0x20];
}

