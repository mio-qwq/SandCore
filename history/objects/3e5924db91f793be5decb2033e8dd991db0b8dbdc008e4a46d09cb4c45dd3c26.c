    u32 *frame=(u32 *)sc_alloc((u32)(width*height*4));
    if(!frame)return 2;
    for(int i=0;i<width*height;i++)frame[i]=0xFF000000u|SCN_SHADE;
    sc_frame32(win,frame,(u32)(width*height*4));
    scene_probe[0]=1;
